import "./global.css";
import type { Metadata, Viewport } from "next";
import type { ReactNode } from "react";
import localFont from "next/font/local";
import { RootProvider } from "fumadocs-ui/provider/next";
import { Analytics } from "@vercel/analytics/next";
import { SpeedInsights } from "@vercel/speed-insights/next";
import { SITE_NAME, SITE_URL } from "@/lib/site";

/**
 * Two faces, each doing the job it exists for.
 *
 * SPACE GROTESK is the brand face — the Oxagen house typeface, vendored from
 * the kit by `scripts/sync-brand-assets.mjs`. It is not a preference: the
 * `stella*` wordmark is this font's own outlines at weight 600, so setting the
 * site in anything else would put the name in the nav and the name in a
 * sentence in two unrelated designs. 700 display, 600 headings, 500 UI,
 * 400 body.
 *
 * JETBRAINS MONO stays, for code and terminal transcripts only. The house rule
 * is "Space Grotesk is not a code face", and this site is largely a picture of
 * a terminal — column alignment in a transcript is load-bearing, not
 * decorative. What changed is its scope: it used to be BOTH faces, on the
 * argument that a product living in a terminal should speak in monospace end
 * to end. The house system settles that the other way, and the two families
 * now split exactly where the kit puts the line.
 */
const sans = localFont({
  src: [
    { path: "../fonts/space-grotesk-latin-400.woff2", weight: "400", style: "normal" },
    { path: "../fonts/space-grotesk-latin-500.woff2", weight: "500", style: "normal" },
    { path: "../fonts/space-grotesk-latin-600.woff2", weight: "600", style: "normal" },
    { path: "../fonts/space-grotesk-latin-700.woff2", weight: "700", style: "normal" },
  ],
  variable: "--font-stella-sans",
  display: "swap",
});

const mono = localFont({
  src: [
    { path: "../fonts/jetbrains-mono-latin-400-normal.woff2", weight: "400", style: "normal" },
    { path: "../fonts/jetbrains-mono-latin-500-normal.woff2", weight: "500", style: "normal" },
    { path: "../fonts/jetbrains-mono-latin-700-normal.woff2", weight: "700", style: "normal" },
  ],
  variable: "--font-stella-mono",
  display: "swap",
});

const SITE_DESCRIPTION =
  "Documentation for stella — the terminal agent. Fast, BYOK, model-agnostic, and it proves its work finished.";
// OG + Twitter card images are generated by src/app/opengraph-image.tsx and
// twitter-image.tsx (next/og) — Next wires them into metadata.

export const metadata: Metadata = {
  metadataBase: new URL(SITE_URL),
  // lowercase always — the brand name never takes a capital, even in a tab.
  title: {
    default: "stella — docs",
    template: "%s — stella docs",
  },
  description: SITE_DESCRIPTION,
  alternates: { canonical: SITE_URL },
  applicationName: SITE_NAME,
  appleWebApp: {
    capable: true,
    title: "stella",
    statusBarStyle: "black-translucent",
  },
  openGraph: {
    title: "stella — docs",
    description: SITE_DESCRIPTION,
    url: SITE_URL,
    siteName: SITE_NAME,
    type: "website",
  },
  twitter: {
    card: "summary_large_image",
    title: "stella — docs",
    description: SITE_DESCRIPTION,
  },
};

export const viewport: Viewport = {
  width: "device-width",
  initialScale: 1,
  themeColor: [
    { media: "(prefers-color-scheme: dark)", color: "#10100f" }, // --st-bg
    { media: "(prefers-color-scheme: light)", color: "#f2eee5" }, // --st-paper-ground
  ],
};

export default function RootLayout({ children }: { children: ReactNode }) {
  return (
    <html lang="en" suppressHydrationWarning className={`${sans.variable} ${mono.variable}`}>
      <body className="flex min-h-screen flex-col">
        {/* First focusable node in the document, ahead of the Fumadocs header
         * and (on /docs) a ~90-link sidebar. Both route groups expose a
         * `#content` target at the top of their reading order. */}
        <a className="skip-link" href="#content">
          Skip to content
        </a>
        <RootProvider>{children}</RootProvider>
        {/* Vercel Web Analytics + Core Web Vitals. Both are cookie-less,
            no-op outside Vercel deployments, and served same-origin from
            /_vercel/* — nothing third-party enters the page. */}
        <Analytics />
        <SpeedInsights />
      </body>
    </html>
  );
}
