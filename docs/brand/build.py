#!/usr/bin/env python3
"""Regenerate every Stella brand asset -- and every colour token -- from one source.

The identity is a wordmark, one mark, and one palette:

  wordmark  lowercase "stella", Space Grotesk Medium (wght 500) tracked -0.02em,
            converted to outlines so nothing at build or render time needs a font
  mark      a six-arm concave asterisk. It reads as `*` -- glob, wildcard, the
            first character of a doc comment -- and as a stellar burst. Used only
            where a square or very small footprint rules the wordmark out.
  palette   gold on deep navy: a star against night sky. Defined once in
            tokens.json and generated into every consumer.

The repo used to carry three rival palettes -- the docs site's neutral paper-&-
ink, the TUI's aurora-on-navy, and the observatory's cyan. They are collapsed
into tokens.json, and this script is what keeps them collapsed: it writes the
TUI's palette.rs, the docs site's tokens.css, and the observatory's :root block
from those exact values. Nothing downstream is hand-synced.

The wordmark stays ink/paper; the mark carries the gold. That asymmetry is
deliberate -- gold is 1.35:1 on white, so it can never be text on a light
ground. See tokens.json `rules` and README.md's Colour section.

Every run verifies tokens.json's `contracts` (pairs that must meet WCAG AA) and
`forbidden` (pairs that must stay illegible, so the asymmetry cannot be
"fixed" by accident). A token edit that breaks either fails the build with the
measured ratio instead of shipping.

Usage:  make brand          (or)  python3 docs/brand/build.py

Requires: fonttools, uharfbuzz (pip) and rsvg-convert (brew install librsvg).
The typeface is fetched once and cached under docs/brand/.cache/.
"""

from __future__ import annotations

import hashlib
import importlib.util
import json
import math
import re
import shutil
import subprocess
import sys
import urllib.request
from pathlib import Path

# ---------------------------------------------------------------- configuration

FONT_URL = "https://github.com/google/fonts/raw/main/ofl/spacegrotesk/SpaceGrotesk%5Bwght%5D.ttf"
FONT_SHA256 = "acad6de1fc93436f5c0f1f4137751ef04f1aea3063e7036535970ffcfbd79f72"
FONT_WEIGHT = 500  # Medium
TRACKING_EM = -0.02  # tightened from the default fit; see docs/brand/README.md

WORD = "stella"

ROOT = Path(__file__).resolve().parents[2]
BRAND = ROOT / "docs" / "brand"
CACHE = BRAND / ".cache"
SITE_BRAND = ROOT / "stella-docs" / "public" / "brand"
SITE_ICONS = ROOT / "stella-docs" / "public" / "icons"
SITE_APP = ROOT / "stella-docs" / "src" / "app"
OBSERVATORY = ROOT / "stella-observatory" / "src" / "assets"
TUI = ROOT / "stella-tui" / "src"

GENERATED = "Generated by docs/brand/build.py (edit that, not this file)."
TOKENS_NOTE = "Generated from docs/brand/tokens.json by docs/brand/build.py (edit those, not this file)."


# ----------------------------------------------------------------------- tokens

TOKENS = json.loads((BRAND / "tokens.json").read_text())
# name -> "#RRGGBB", flattened across groups. Names are unique across the whole
# palette by construction; the check below is what guarantees it stays that way.
COLOR: dict[str, str] = {}
for _group in TOKENS["groups"]:
    for _token in _group["tokens"]:
        if _token["name"] in COLOR:
            sys.exit(f"duplicate token name in tokens.json: {_token['name']}")
        COLOR[_token["name"]] = _token["value"]

# The three cuts the wordmark and mark ship in. The wordmark stays ink/paper;
# only the mark takes the gold (tokens.json rule 4).
INK = COLOR["ink"]
PAPER = COLOR["paper"]
GOLD = COLOR["gold"]
NAVY = COLOR["night"]


def _rgb(value: str) -> tuple[int, int, int]:
    h = value.lstrip("#")
    return int(h[0:2], 16), int(h[2:4], 16), int(h[4:6], 16)


def _luminance(value: str) -> float:
    """WCAG 2.1 relative luminance."""

    def channel(raw: int) -> float:
        c = raw / 255.0
        return c / 12.92 if c <= 0.04045 else ((c + 0.055) / 1.055) ** 2.4

    r, g, b = (channel(c) for c in _rgb(value))
    return 0.2126 * r + 0.7152 * g + 0.0722 * b


def contrast(fg: str, bg: str) -> float:
    """WCAG 2.1 contrast ratio between two hex colours, 1.0 -- 21.0."""
    a, b = _luminance(fg), _luminance(bg)
    hi, lo = max(a, b), min(a, b)
    return (hi + 0.05) / (lo + 0.05)


def verify_contrast() -> None:
    """Enforce tokens.json's `contracts` and `forbidden`.

    `contracts` are pairs that must clear a WCAG floor. `forbidden` are pairs
    that must *stay* below one -- the gold-on-paper asymmetry is load-bearing,
    so a well-meaning edit that made gold legible on white would silently
    dissolve rule 1. Both directions fail loudly, with the measured ratio.
    """
    failures: list[str] = []

    for rule in TOKENS["contracts"]:
        fg, bg, floor = rule["fg"], rule["bg"], rule["min"]
        ratio = contrast(COLOR[fg], COLOR[bg])
        if ratio < floor:
            failures.append(
                f"  {fg} on {bg}: {ratio:.2f}:1 -- needs {floor}:1 ({rule['note']})"
            )

    for rule in TOKENS["forbidden"]:
        fg, bg, ceiling = rule["fg"], rule["bg"], rule["max"]
        ratio = contrast(COLOR[fg], COLOR[bg])
        if ratio >= ceiling:
            failures.append(
                f"  {fg} on {bg}: {ratio:.2f}:1 -- must stay under {ceiling}:1. {rule['why']}"
            )

    if failures:
        sys.exit(
            "tokens.json fails its own contrast contract:\n"
            + "\n".join(failures)
            + "\n\nFix the token values, or amend the contract in tokens.json if "
            "the design genuinely changed."
        )

    print(
        f"contrast  {len(TOKENS['contracts'])} contracts, "
        f"{len(TOKENS['forbidden'])} forbidden pairs -- all hold"
    )


def replace_region(text: str, marker: str, body: str) -> str:
    """Swap the lines between `BEGIN <marker>` / `END <marker>` for `body`.

    Used for the files this script only partly owns -- the observatory's single
    HTML page and the brand README -- so a generated block can live inside a
    hand-written file without the generator claiming the whole thing.
    """
    pattern = re.compile(
        rf"([ \t]*(?://|/\*|<!--|#)[^\n]*BEGIN[^\n]*{re.escape(marker)}[^\n]*\n)"
        rf".*?"
        rf"([ \t]*(?://|/\*|<!--|#)[^\n]*END[^\n]*{re.escape(marker)}[^\n]*)",
        re.DOTALL,
    )
    if not pattern.search(text):
        sys.exit(
            f"could not find the generated region markers for {marker!r}.\n"
            f"  Expected a 'BEGIN {marker}' ... 'END {marker}' comment pair."
        )
    return pattern.sub(lambda m: f"{m.group(1)}{body}{m.group(2)}", text, count=1)


# ------------------------------------------------------------------------ fonts


def font_path() -> Path:
    CACHE.mkdir(parents=True, exist_ok=True)
    dest = CACHE / "SpaceGrotesk[wght].ttf"
    if dest.exists() and hashlib.sha256(dest.read_bytes()).hexdigest() == FONT_SHA256:
        return dest
    print(f"fetching {FONT_URL}")
    with urllib.request.urlopen(FONT_URL) as response:  # noqa: S310 - pinned URL
        blob = response.read()
    digest = hashlib.sha256(blob).hexdigest()
    if digest != FONT_SHA256:
        sys.exit(f"font hash mismatch: expected {FONT_SHA256}, got {digest}")
    dest.write_bytes(blob)
    return dest


def outline_word(word: str) -> tuple[str, tuple[float, float, float, float]]:
    """Shape `word` and return (path data, ink bounding box).

    Coordinates are y-down with the baseline at y=0, so the emitted path drops
    straight into an SVG with no wrapping transform.
    """
    import uharfbuzz as hb
    from fontTools.pens.boundsPen import BoundsPen
    from fontTools.pens.svgPathPen import SVGPathPen
    from fontTools.pens.transformPen import TransformPen
    from fontTools.misc.transform import Transform
    from fontTools.ttLib import TTFont
    from fontTools.varLib import instancer

    source = font_path()

    # Pin the variable font to Medium so shaping and outlines agree.
    ttfont = instancer.instantiateVariableFont(
        TTFont(source), {"wght": FONT_WEIGHT}, inplace=False
    )
    pinned = CACHE / f"SpaceGrotesk-{FONT_WEIGHT}.ttf"
    ttfont.save(pinned)

    upem = ttfont["head"].unitsPerEm
    tracking = TRACKING_EM * upem

    # HarfBuzz gives us real shaping -- kerning included -- rather than naive
    # advance-width stacking.
    blob = hb.Blob.from_file_path(str(pinned))
    hbfont = hb.Font(hb.Face(blob))
    buf = hb.Buffer()
    buf.add_str(word)
    buf.guess_segment_properties()
    hb.shape(hbfont, buf)

    glyph_set = ttfont.getGlyphSet()
    glyph_order = ttfont.getGlyphOrder()

    segments: list[str] = []
    bounds = BoundsPen(glyph_set)
    pen_x = 0.0

    for index, (info, pos) in enumerate(zip(buf.glyph_infos, buf.glyph_positions)):
        name = glyph_order[info.codepoint]
        # Flip y (font units are y-up, SVG is y-down) and place at the pen.
        transform = Transform(1, 0, 0, -1, pen_x + pos.x_offset, -pos.y_offset)

        svg_pen = SVGPathPen(glyph_set, ntos=lambda v: f"{v:.1f}")
        glyph_set[name].draw(TransformPen(svg_pen, transform))
        drawn = svg_pen.getCommands()
        if drawn:
            segments.append(drawn)
        glyph_set[name].draw(TransformPen(bounds, transform))

        pen_x += pos.x_advance
        if index < len(buf.glyph_infos) - 1:
            pen_x += tracking

    if bounds.bounds is None:
        sys.exit("no outlines produced")
    return " ".join(segments), bounds.bounds


# ------------------------------------------------------------------------- mark


def asterisk_path(
    cx: float,
    cy: float,
    radius: float,
    *,
    arms: int = 6,
    concavity: float = 0.52,
    waist: float = 0.31,
    tip: float = 0.055,
) -> str:
    """A six-arm asterisk with concave flanks, as one transform-free path.

    Each arm is a wedge: wide at the hub, waisted by a quadratic pulled inward,
    and capped with a small radius so the tips read as drawn rather than clipped.
    """
    half = radius * waist
    tip_r = radius * tip
    control = half * (1 - concavity)
    waist_y = -radius * 0.55

    def place(x: float, y: float, angle: float) -> tuple[float, float]:
        rad = math.radians(angle)
        sin, cos = math.sin(rad), math.cos(rad)
        return (cx + x * cos - y * sin, cy + x * sin + y * cos)

    def fmt(point: tuple[float, float]) -> str:
        return f"{point[0]:.2f} {point[1]:.2f}"

    parts: list[str] = []
    for index in range(arms):
        angle = index * 360.0 / arms
        start = place(-half, 0, angle)
        left_ctl = place(-control, waist_y, angle)
        left_tip = place(-tip_r, -radius, angle)
        cap_ctl = place(0, -radius - tip_r, angle)
        right_tip = place(tip_r, -radius, angle)
        right_ctl = place(control, waist_y, angle)
        end = place(half, 0, angle)
        parts.append(
            f"M {fmt(start)} Q {fmt(left_ctl)} {fmt(left_tip)} "
            f"Q {fmt(cap_ctl)} {fmt(right_tip)} "
            f"Q {fmt(right_ctl)} {fmt(end)} Z"
        )
    return " ".join(parts)


