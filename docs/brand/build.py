def svg(body: str, view_box: str, *, width: float, height: float, label: str) -> str:
    return (
        f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="{view_box}" '
        f'width="{width:.0f}" height="{height:.0f}" fill="none" '
        f'role="img" aria-label="{label}">\n'
        f"  <!-- {GENERATED} -->\n"
        f"{body}\n"
        f"</svg>\n"
    )


def write(path: Path, text: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text)
    print(f"  {path.relative_to(ROOT)}")


def rasterize(source: Path, dest: Path, size: int) -> None:
    subprocess.run(
        ["rsvg-convert", "-w", str(size), "-h", str(size), str(source), "-o", str(dest)],
        check=True,
    )
    print(f"  {dest.relative_to(ROOT)} ({size}px)")


def emit_palette_rs() -> None:
    """stella-tui/src/palette.rs -- raw colour consts, nothing semantic.

    theme.rs keeps the semantic layer (ACCENT, OK, RULE, the status mapping) and
    consumes these. Splitting them is what lets a recolour be a tokens.json edit
    instead of a hunt through the crate.
    """
    lines = [
        f"//! {TOKENS_NOTE}",
        "//!",
        "//! Raw palette values -- the single normative colour source, shared with",
        "//! the docs site and the observatory. Nothing here is semantic: for role",
        "//! names (accent, ink, rule, status) see [`crate::theme`], which is the",
        "//! only module that should be referencing these directly.",
        "//!",
        f"//! The identity is {TOKENS['identity']}.",
        "",
        "use ratatui::style::Color;",
        "",
    ]
    for group in TOKENS["groups"]:
        lines.append(f"// ── {group['title']} {'─' * max(0, 60 - len(group['title']))}")
        lines.append("//")
        for chunk in _wrap(group["doc"], 74):
            lines.append(f"// {chunk}")
        lines.append("")
        for token in group["tokens"]:
            for chunk in _wrap(token["doc"], 74):
                lines.append(f"/// {chunk}")
            r, g, b = _rgb(token["value"])
            lines.append(
                f"pub const {_rust_name(token['name'])}: Color = "
                f"Color::Rgb(0x{r:02X}, 0x{g:02X}, 0x{b:02X});"
            )
            lines.append("")

    names = [t["name"] for group in TOKENS["groups"] for t in group["tokens"]]
    lines.append("/// Every palette colour, paired with its tokens.json name.")
    lines.append("///")
    lines.append("/// Lets a test walk the whole palette -- see theme.rs's colour-depth")
    lines.append("/// fallback coverage check -- without a hand-maintained second list.")
    lines.append(f"pub const ALL: [(&str, Color); {len(names)}] = [")
    for name in names:
        lines.append(f'    ("{name}", {_rust_name(name)}),')
    lines.append("];")
    write(TUI / "palette.rs", "\n".join(lines) + "\n")


def emit_tokens_css() -> None:
    """stella-docs/src/app/tokens.css -- the raw palette as custom properties.

    Mode-aware semantics (which token is "foreground" in dark vs light) stay in
    global.css. This file is the CSS twin of palette.rs: values only.
    """
    lines = [
        "/**",
        f" * {TOKENS_NOTE}",
        " *",
        " * Raw palette values, imported by global.css. Nothing here is mode-aware:",
        " * global.css maps these onto the light/dark semantic layer, the same way",
        " * stella-tui's theme.rs maps palette.rs.",
        " *",
        f" * The identity is {TOKENS['identity']}.",
        " */",
        "",
        ":root {",
    ]
    for group in TOKENS["groups"]:
        lines.append(f"  /* {group['title']} — {group['doc'].split('.')[0]}. */")
        for token in group["tokens"]:
            lines.append(f"  --stella-{token['name']}: {token['value'].lower()};")
        lines.append("")
    if lines[-1] == "":
        lines.pop()
    lines.append("}")
    write(SITE_APP / "tokens.css", "\n".join(lines) + "\n")


def emit_observatory_tokens() -> None:
    """Rewrite the observatory's :root colour block in place.

    The observatory is a single self-contained HTML page served by `include_str!`
    and guarded by a test that forbids any external reference, so its tokens must
    stay inlined -- no @import of tokens.css. Only the region between the markers
    is generated; the font stacks and everything else in :root are left alone.
    """
    index = OBSERVATORY / "index.html"
    text = index.read_text()

    rows = [
        "  --night:{night}; --ground:{ground}; --surface:{surface};",
        "  --raised:{raised}; --hairline:{hairline};",
        "  --gold:{gold}; --gold-deep:{gold_deep};",
        "  --text:{text_primary}; --text-2:{text_secondary}; --text-3:{text_tertiary};",
        "  --ok:{success}; --warn:{warning}; --bad:{danger};",
    ]
    values = {key.replace("-", "_"): value.upper() for key, value in COLOR.items()}
    body = "\n".join(row.format(**values) for row in rows)
    body = (
        f"{body}\n"
        "  /* Semantic alias. The dashboard is dark-only, so this resolves once.\n"
        "     Only ONE alias, and only for brand/active/progress: the page's quiet\n"
        "     structural labels take --text-3. An `--accent-2` here would just be a\n"
        "     licence to paint everything gold, which is what rule 3 forbids. */\n"
        "  --accent:var(--gold);\n"
    )
    write(index, replace_region(text, "brand palette", body))


