def _rust_name(name: str) -> str:
    return name.replace("-", "_").upper()


def _wrap(text: str, width: int) -> list[str]:
    words, lines, current = text.split(), [], ""
    for word in words:
        candidate = f"{current} {word}".strip()
        if len(candidate) > width and current:
            lines.append(current)
            current = word
        else:
            current = candidate
    if current:
        lines.append(current)
    return lines or [""]


def main() -> None:
    if not shutil.which("rsvg-convert"):
        sys.exit("rsvg-convert not found — brew install librsvg")
    missing = [
        package
        for module, package in (("fontTools", "fonttools"), ("uharfbuzz", "uharfbuzz"))
        if importlib.util.find_spec(module) is None
    ]
    if missing:
        sys.exit(
            f"missing Python packages: {', '.join(missing)}\n"
            f"  pip install {' '.join(missing)}"
        )

    # Before anything is written: if the palette does not satisfy its own
    # contract there is no point generating assets from it.
    verify_contrast()

    print("colour tokens")
    emit_palette_rs()
    emit_tokens_css()
    emit_observatory_tokens()
    emit_readme_colour()

    print("wordmark")
    path_data, (x0, y0, x1, y1) = outline_word(WORD)
    # Pad the ink box by a hair so antialiased edges are never clipped.
    pad = (x1 - x0) * 0.004
    x0, y0, x1, y1 = x0 - pad, y0 - pad, x1 + pad, y1 + pad
    w, h = x1 - x0, y1 - y0
    view = f"{x0:.1f} {y0:.1f} {w:.1f} {h:.1f}"
    # Nominal display size: 28px tall, the docs-site nav height.
    nominal_h = 28.0
    nominal_w = nominal_h * w / h

    for name, fill in (
        ("wordmark.svg", "currentColor"),
        ("wordmark-ink.svg", INK),
        ("wordmark-paper.svg", PAPER),
    ):
        body = f'  <path d="{path_data}" fill="{fill}"/>'
        write(
            BRAND / name,
            svg(body, view, width=nominal_w, height=nominal_h, label="Stella"),
        )

    print("mark")
    mark_box = 100.0
    mark = asterisk_path(mark_box / 2, mark_box / 2, mark_box * 0.46)
    mark_view = f"0 0 {mark_box:.0f} {mark_box:.0f}"
    # The mark is the one place the brand hue lives -- hence the gold cut, which
    # the wordmark deliberately has no counterpart for (tokens.json rule 4).
    for name, fill in (
        ("mark.svg", "currentColor"),
        ("mark-ink.svg", INK),
        ("mark-paper.svg", PAPER),
        ("mark-gold.svg", GOLD),
    ):
        write(
            BRAND / name,
            svg(
                f'  <path d="{mark}" fill="{fill}"/>',
                mark_view,
                width=mark_box,
                height=mark_box,
                label="Stella",
            ),
        )

    print("lockup")
    # Mark set to cap height, one wordmark-x-height of air between the two.
    for name, fill in (("lockup-ink.svg", INK), ("lockup-paper.svg", PAPER)):
        mark_size = h * 0.94
        gap = h * 0.42
        total_w = mark_size + gap + w
        lock_view = f"0 0 {total_w:.1f} {h:.1f}"
        inner = asterisk_path(mark_size / 2, h / 2, mark_size * 0.46)
        body = (
            f'  <path d="{inner}" fill="{fill}"/>\n'
            f'  <g transform="translate({mark_size + gap - x0:.1f} {-y0:.1f})">'
            f'<path d="{path_data}" fill="{fill}"/></g>'
        )
        write(
            BRAND / name,
            svg(
                body,
                lock_view,
                width=nominal_h * total_w / h,
                height=nominal_h,
                label="Stella",
            ),
        )

    print("icons")
    # Tile + mark. A tile keeps the favicon legible against any tab colour, which
    # a bare glyph on transparency does not. Gold on navy, not paper on ink: at
    # 16px the icon is the only brand surface a user sees, so it carries the hue.
    def tile(size: float, mark_ratio: float, radius_ratio: float) -> str:
        radius = size * radius_ratio
        inner = asterisk_path(size / 2, size / 2, size * mark_ratio / 2)
        return (
            f'  <rect width="{size:.0f}" height="{size:.0f}" rx="{radius:.1f}" fill="{NAVY}"/>\n'
            f'  <path d="{inner}" fill="{GOLD}"/>'
        )

    favicon = svg(
        tile(200, 0.70, 0.22), "0 0 200 200", width=200, height=200, label="Stella"
    )
    appicon = svg(
        tile(512, 0.58, 0.2237), "0 0 512 512", width=512, height=512, label="Stella"
    )
    # Maskable art gets cropped to the inner ~80%; keep the mark well inside.
    maskable = svg(
        f'  <rect width="512" height="512" fill="{NAVY}"/>\n'
        f'  <path d="{asterisk_path(256, 256, 512 * 0.42 / 2)}" fill="{GOLD}"/>',
        "0 0 512 512",
        width=512,
        height=512,
        label="Stella",
    )

    write(BRAND / "favicon.svg", favicon)
    write(BRAND / "appicon.svg", appicon)
    write(CACHE / "maskable.svg", maskable)

    print("site copies")
    # The site consumes docs/brand/ verbatim. Copying here is what keeps the two
    # trees from drifting the way the previous generation did.
    for name in (
        "wordmark.svg",
        "wordmark-ink.svg",
        "wordmark-paper.svg",
        "mark.svg",
        "mark-ink.svg",
        "mark-paper.svg",
        "mark-gold.svg",
        "lockup-ink.svg",
        "lockup-paper.svg",
    ):
        shutil.copyfile(BRAND / name, SITE_BRAND / name)
        print(f"  {(SITE_BRAND / name).relative_to(ROOT)}")

    write(SITE_ICONS / "favicon.svg", favicon)
    write(SITE_ICONS / "appicon.svg", appicon)
    write(SITE_APP / "icon.svg", favicon)  # Next.js file convention
    # The observatory serves this as an <img> and as its favicon, so it needs a
    # literal colour -- currentColor would resolve to black on the navy ground.
    # It takes the gold cut: the mark carries the hue, the wordmark stays paper.
    shutil.copyfile(BRAND / "mark-gold.svg", OBSERVATORY / "mark.svg")
    print(f"  {(OBSERVATORY / 'mark.svg').relative_to(ROOT)}")
    shutil.copyfile(BRAND / "wordmark-paper.svg", OBSERVATORY / "wordmark.svg")
    print(f"  {(OBSERVATORY / 'wordmark.svg').relative_to(ROOT)}")

    print("site brand module")
    # Emitting the geometry as TS keeps the landing page's inline mark and the
    # generated OG card on exactly the same paths as the SVG assets.
    write(
        ROOT / "stella-docs" / "src" / "components" / "brand.tsx",
        f"""// {GENERATED}
//
// Inline brand geometry. Both components paint with `currentColor`, so they
// invert with the theme without needing a per-mode asset.

export const WORDMARK_VIEW_BOX = "{view}";
export const WORDMARK_PATH =
  "{path_data}";

export const MARK_VIEW_BOX = "{mark_view}";
export const MARK_PATH =
  "{mark}";

export function Wordmark({{ className }}: {{ className?: string }}) {{
  return (
    <svg
      viewBox={{WORDMARK_VIEW_BOX}}
      fill="currentColor"
      className={{className}}
      role="img"
      aria-label="Stella"
    >
      <path d={{WORDMARK_PATH}} />
    </svg>
  );
}}

export function Mark({{ className }}: {{ className?: string }}) {{
  return (
    <svg viewBox={{MARK_VIEW_BOX}} fill="currentColor" className={{className}} aria-hidden>
      <path d={{MARK_PATH}} />
    </svg>
  );
}}
""",
    )

    print("rasters")
    for size in (16, 32, 48):
        rasterize(BRAND / "favicon.svg", SITE_ICONS / f"favicon-{size}.png", size)
    rasterize(BRAND / "appicon.svg", SITE_ICONS / "apple-touch-icon-180.png", 180)
    rasterize(BRAND / "appicon.svg", SITE_APP / "apple-icon.png", 180)
    for size in (192, 512):
        rasterize(BRAND / "appicon.svg", SITE_ICONS / f"icon-{size}.png", size)
        rasterize(CACHE / "maskable.svg", SITE_ICONS / f"maskable-{size}.png", size)

    print(f"\nwordmark ink box {w:.0f}x{h:.0f} units, aspect {w / h:.3f}")


