#[test]
fn advancing_walks_every_lens_and_ends_in_watch_not_termination() {
    let mut current = "rubric";
    let mut walked = vec![current];
    loop {
        let next = advance(current);
        if next == WATCH {
            break;
        }
        walked.push(next);
        current = next;
    }
    assert_eq!(walked.len(), LENSES.len(), "every lens is reachable");
    assert_eq!(advance("soak"), WATCH);
    assert_eq!(advance(WATCH), WATCH, "watch is terminal, not an error");
    assert_eq!(advance("no-such-lens"), WATCH);
}

/// #1549's contract: no aperture is silently a no-op. Every lens either names
/// a concrete command a cycle runs and interprets, or is on the record as
/// model-only — so the model always knows whether it is working aided.
#[test]
fn every_lens_declares_its_tooling_or_admits_it_has_none() {
    for l in LENSES {
        match l.tooling {
            Tooling::Command { run, interpret } => {
                assert!(!run.trim().is_empty(), "{} names an empty command", l.name);
                assert!(
                    !interpret.trim().is_empty(),
                    "{} says nothing about interpreting its tool",
                    l.name
                );
            }
            Tooling::ModelOnly { note } => {
                assert!(
                    !note.trim().is_empty(),
                    "{} is model-only with no note — a silent no-op",
                    l.name
                );
            }
        }
    }
    let heavy: Vec<&str> = LENSES
        .iter()
        .filter(|l| l.heavy_only)
        .map(|l| l.name)
        .collect();
    assert_eq!(
        heavy,
        ["performance", "soak"],
        "the lenses that spend real money are gated on the heavy tier"
    );
}

