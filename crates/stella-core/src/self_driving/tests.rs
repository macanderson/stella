fn ledger_row(cycle_n: u64, fixed: u64, filed: u64, new: u64, gate: &str) -> CycleRecord {
    CycleRecord {
        fixed,
        filed,
        new_findings: new,
        gate: gate.into(),
        dry: new == 0,
        ..cycle(cycle_n, "rubric", new == 0)
    }
}

#[test]
fn three_zero_fix_cycles_raise_stuck_and_a_healthy_loop_raises_nothing() {
    let stuck: Vec<CycleRecord> = (1..=3).map(|i| ledger_row(i, 0, 1, 1, "green")).collect();
    let codes: Vec<&str> = metrics(&stuck).signals.iter().map(|s| s.code).collect();
    assert!(codes.contains(&"STUCK"), "got {codes:?}");

    let healthy: Vec<CycleRecord> = (1..=6).map(|i| ledger_row(i, 4, 1, 2, "green")).collect();
    let m = metrics(&healthy);
    assert!(
        m.signals.is_empty(),
        "a dashboard that always warns teaches the reader to ignore it: {:?}",
        m.signals
    );
    assert_eq!(m.fixed, 24);
}

#[test]
fn noisy_and_fragile_fire_on_their_exact_thresholds() {
    // n=5, discovery 2 (2*2 < 5), filed 11 (> 2*5): dedup is leaking.
    let mut rows: Vec<CycleRecord> = (1..=4).map(|i| ledger_row(i, 1, 2, 0, "green")).collect();
    rows.push(ledger_row(5, 1, 3, 2, "green"));
    let codes: Vec<&str> = metrics(&rows).signals.iter().map(|s| s.code).collect();
    assert!(codes.contains(&"NOISY"), "got {codes:?}");

    let rows: Vec<CycleRecord> = (1..=4)
        .map(|i| ledger_row(i, 1, 0, 1, if i <= 2 { "red" } else { "green" }))
        .collect();
    let codes: Vec<&str> = metrics(&rows).signals.iter().map(|s| s.code).collect();
    assert!(codes.contains(&"FRAGILE"), "got {codes:?}");
}

