use super::*;

// ---------------------------------------------------------------------------
// digest — the dedup key the termination oracle rests on
// ---------------------------------------------------------------------------

/// Byte-parity with the shell pipeline that built every existing `seen.txt`
/// (`tr | sed | shasum -a 256 | cut -c1-16`). These hashes were generated by
/// running that pipeline; a divergence here re-reports every previously
/// triaged finding as new.
#[test]
fn digest_matches_the_shell_pipeline_goldens() {
    assert_eq!(
        finding_digest("crates/stella-core/src/driver.rs:812 retry counter never reset"),
        "a9efcba568ece91c"
    );
    assert_eq!(
        finding_digest("  Padded   And   Mixed:99Case  "),
        "a14d1857fdef58c3"
    );
    assert_eq!(
        finding_digest("unicode — em-dash · and:42:43 twice"),
        "034bf1e7a3e3b8a4"
    );
}

#[test]
fn line_number_case_and_whitespace_normalize_to_one_finding() {
    let a = finding_digest("crates/stella-core/src/driver.rs:812 retry counter never reset");
    let b = finding_digest("crates/stella-core/src/driver.rs:940    Retry Counter Never Reset");
    assert_eq!(a, b, "the same defect at a shifted line is one finding");

    let c = finding_digest("crates/stella-cli/src/agent.rs a different defect entirely");
    assert_ne!(a, c, "distinct findings keep distinct digests");
}

proptest! {
    /// The normalizations the digest promises, swept over ASCII descriptions
    /// (the shell's `tr` was byte-wise, so parity is an ASCII contract).
    #[test]
    fn digest_is_invariant_under_padding_case_and_line_numbers(s in "[ -~]{0,80}") {
        let base = finding_digest(&s);
        prop_assert_eq!(&finding_digest(&format!("  {s}  ")), &base);
        prop_assert_eq!(&finding_digest(&s.to_ascii_uppercase()), &base);
        prop_assert_eq!(
            &finding_digest(&format!("{s}:123 tail")),
            &finding_digest(&format!("{s}:7 tail"))
        );
    }
}

