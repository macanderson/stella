/// The ledger is written here, read by the observatory, and appended to by
/// future writers; a round-trip that drops unknown keys would destroy what it
/// did not understand (invariant 4's discipline applied to a file format).
#[test]
fn cycle_records_round_trip_and_preserve_foreign_keys() {
    let raw = json!({
        "cycle": 7, "run_id": "r-1", "ended_at": "2026-08-05T00:00:00Z",
        "ended_at_unix": 1, "fixed": 2, "filed": 1, "new_findings": 0,
        "bench": "loop", "gate": "green", "prs": ["#9"], "tier": "normal",
        "aperture": "rubric", "lens_tool": "/ultraudit", "outcome": "ok",
        "minutes": 12, "dry": true,
        "a_future_key": {"nested": true}
    });
    let rec: CycleRecord = serde_json::from_value(raw.clone()).expect("parses");
    assert_eq!(rec.lens_tool.as_deref(), Some("/ultraudit"));
    let back = serde_json::to_value(&rec).expect("serializes");
    assert_eq!(back, raw, "byte-stable round-trip, foreign keys included");
}
