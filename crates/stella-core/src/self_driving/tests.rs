#[test]
fn three_clean_runs_raise_the_parallel_ceiling_exactly_once() {
    let limits = AimdLimits::default();
    let mut cal = Calibration::seeded(&limits);
    for _ in 0..3 {
        calibrate(&mut cal, CycleOutcome::Ok, &limits);
    }
    assert_eq!(cal.parallel_ceiling, 3);
    assert_eq!(cal.clean_run, 3);
}

#[test]
fn a_resource_failure_halves_batch_and_resets_parallel_to_serial() {
    let limits = AimdLimits::default();
    let mut cal = Calibration::seeded(&limits);
    for _ in 0..3 {
        calibrate(&mut cal, CycleOutcome::Ok, &limits);
    }
    calibrate(&mut cal, CycleOutcome::ResourceFail, &limits);
    assert_eq!(
        (cal.batch_ceiling, cal.parallel_ceiling, cal.clean_run),
        (10, 1, 0)
    );
}

/// The regression that shipped in the shell driver: rebuilding the document
/// from the keys this module owns silently discarded every key it did not —
/// `last_clean_head` among them, leaving watch mode unable to ever sleep.
#[test]
fn calibrate_preserves_keys_it_does_not_own() {
    let raw = r#"{"batch_ceiling":20,"parallel_ceiling":2,"clean_run":0,
                  "note":"seeded","last_clean_head":"deadbeef"}"#;
    let mut cal: Calibration = serde_json::from_str(raw).expect("calibration parses");
    calibrate(&mut cal, CycleOutcome::Ok, &AimdLimits::default());
    let out = serde_json::to_value(&cal).expect("serializes");
    assert_eq!(out["last_clean_head"], "deadbeef");
}

proptest! {
    /// Whatever the evidence says, the ceilings stay inside the hard bounds —
    /// a controller that can wander out of range needs no adversary.
    #[test]
    fn the_ceilings_never_leave_their_hard_bounds(outcomes in prop::collection::vec(prop::bool::ANY, 0..64)) {
        let limits = AimdLimits::default();
        let mut cal = Calibration::seeded(&limits);
        for ok in outcomes {
            let outcome = if ok { CycleOutcome::Ok } else { CycleOutcome::ResourceFail };
            calibrate(&mut cal, outcome, &limits);
            prop_assert!(cal.batch_ceiling >= limits.batch_min);
            prop_assert!(cal.batch_ceiling <= limits.batch_max);
            prop_assert!(cal.parallel_ceiling >= 1);
            prop_assert!(cal.parallel_ceiling <= limits.parallel_max);
        }
    }
}

