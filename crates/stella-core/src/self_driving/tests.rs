#[test]
fn a_run_the_live_pointer_moved_on_from_reports_crashed() {
    let live = json!({"run_id": "r-new", "phase": "cycle", "heartbeat_unix": 9_990});
    let rows = fold_runs(
        &[run_rec("r-old", "running"), run_rec("r-new", "running")],
        &[],
        Some(&live),
        10_000,
        900,
    );
    let status = |id: &str| {
        rows.iter()
            .find(|r| r.run_id == id)
            .map(|r| r.status.clone())
            .unwrap_or_default()
    };
    assert_eq!(status("r-old"), "crashed");
    assert_eq!(status("r-new"), "running");
}

#[test]
fn last_write_wins_and_cycles_aggregate_into_their_run() {
    let mut c1 = cycle(1, "rubric", false);
    c1.run_id = "r-1".into();
    c1.fixed = 4;
    let mut c2 = cycle(2, "rubric", false);
    c2.run_id = "r-1".into();
    c2.fixed = 2;
    let rows = fold_runs(
        &[
            run_rec("r-1", "running"),
            run_rec("r-1", "completed"),
            run_rec("r-2", "cancelled"),
        ],
        &[c1, c2],
        None,
        10_000,
        900,
    );
    let r1 = rows.iter().find(|r| r.run_id == "r-1").expect("r-1 folded");
    assert_eq!(r1.status, "completed", "last write wins");
    assert_eq!((r1.cycles, r1.fixed), (2, 6));
    assert_eq!(
        rows.iter()
            .find(|r| r.run_id == "r-2")
            .map(|r| r.status.as_str()),
        Some("cancelled")
    );
}

