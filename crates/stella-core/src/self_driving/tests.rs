fn cycle(cycle: u64, aperture: &str, dry: bool) -> CycleRecord {
    CycleRecord {
        cycle,
        run_id: String::new(),
        ended_at: String::new(),
        ended_at_unix: 0,
        fixed: 0,
        filed: 0,
        new_findings: u64::from(!dry),
        bench: String::new(),
        gate: "green".into(),
        prs: Vec::new(),
        tier: "normal".into(),
        aperture: aperture.into(),
        lens_tool: None,
        outcome: "ok".into(),
        minutes: 0,
        dry,
        extra: serde_json::Map::new(),
    }
}

#[test]
fn the_streak_is_scoped_to_the_current_lens() {
    // Two dry cycles advanced rubric; the fresh lens must not inherit them.
    let rows = vec![
        cycle(1, "rubric", false),
        cycle(2, "rubric", true),
        cycle(3, "rubric", true),
    ];
    assert_eq!(dry_streak(&rows, "rubric"), 2);
    assert_eq!(
        dry_streak(&rows, "properties"),
        0,
        "a fresh lens does not inherit the dry tail that opened it"
    );
}

#[test]
fn a_discovering_cycle_between_two_dry_ones_resets_the_streak() {
    let rows = vec![
        cycle(1, "rubric", true),
        cycle(2, "rubric", false),
        cycle(3, "rubric", true),
    ];
    assert_eq!(
        dry_streak(&rows, "rubric"),
        1,
        "dry-noise-dry never advances"
    );
}

proptest! {
    /// The streak is exactly the length of the maximal suffix of records that
    /// are dry AND under the queried lens — no simplification into "dry
    /// records in the tail" survives this.
    #[test]
    fn the_streak_is_the_maximal_matching_suffix(
        spec in prop::collection::vec((prop::bool::ANY, prop::bool::ANY), 0..24)
    ) {
        let rows: Vec<CycleRecord> = spec
            .iter()
            .enumerate()
            .map(|(i, (on_lens, dry))| {
                cycle(i as u64, if *on_lens { "rubric" } else { "properties" }, *dry)
            })
            .collect();
        let expected = rows
            .iter()
            .rev()
            .take_while(|r| r.aperture == "rubric" && r.dry)
            .count() as u32;
        prop_assert_eq!(dry_streak(&rows, "rubric"), expected);
    }
}

// ---------------------------------------------------------------------------
// the governor — the plan is a function of the machine
// ---------------------------------------------------------------------------
//
// One assertion shape for the whole ladder, ported case-for-case from
// scripts/test-self-driving.sh: pin a healthy 8-core / 16 GiB / 50 GiB baseline,
// apply one case's overrides, and compare the WHOLE decision tuple exactly —
// "light with the build still on" and "light with the build forbidden" are
// different decisions, and a single-field check lets one impersonate the
// other.

fn base_supply() -> Supply {
    Supply {
        cpu: 8,
        load1: 1,
        mem_total_gb: 16,
        mem_free_gb: 8,
        disk_free_gb: 50,
        on_battery: false,
        busy: false,
    }
}

fn ceilings() -> Calibration {
    Calibration::seeded(&AimdLimits::default())
}

#[track_caller]
fn assert_plan(supply: Supply, demand: Demand, want: (&str, bool, u32, &str, &str, u32, &str)) {
    let plan = plan_cycle(supply, demand, &ceilings(), Floors::default());
    let got = (
        plan.tier.as_str(),
        plan.local_build,
        plan.parallel,
        plan.scope.as_str(),
        plan.bench.as_str(),
        plan.batch,
        plan.audit.as_str(),
    );
    assert_eq!(got, want, "reason: {}", plan.reason);
}

#[test]
fn the_supply_rungs_decide_the_tier() {
    let d = Demand::default();
    assert_plan(
        base_supply(),
        d,
        ("normal", true, 2, "impacted", "loop", 20, "deep"),
    );

    let big = Supply {
        mem_total_gb: 64,
        mem_free_gb: 32,
        disk_free_gb: 200,
        ..base_supply()
    };
    assert_plan(big, d, ("heavy", true, 2, "workspace", "h2h", 20, "deep"));
    assert_plan(
        Supply { load1: 4, ..big },
        d,
        ("normal", true, 2, "impacted", "loop", 20, "deep"),
    );

    assert_plan(
        Supply {
            disk_free_gb: 5,
            ..base_supply()
        },
        d,
        ("light", false, 2, "ci", "off", 5, "deep"),
    );
    // The floor outranks heavy-class hardware — the first rung wins.
    assert_plan(
        Supply {
            disk_free_gb: 5,
            ..big
        },
        d,
        ("light", false, 2, "ci", "off", 5, "deep"),
    );
    assert_plan(
        Supply {
            busy: true,
            ..base_supply()
        },
        d,
        ("light", false, 1, "ci", "off", 5, "deep"),
    );
    assert_plan(
        Supply {
            mem_free_gb: 2,
            ..base_supply()
        },
        d,
        ("light", false, 1, "ci", "off", 5, "deep"),
    );
    assert_plan(
        Supply {
            on_battery: true,
            ..base_supply()
        },
        d,
        ("light", true, 1, "impacted", "off", 5, "deep"),
    );
    // Saturation sheds the bench arm too — a loop-bench timed on a box whose
    // load already equals its cores is a number the ledger would mislearn
    // from (#1564). The build stays: it runs slower, not wrong.
    assert_plan(
        Supply {
            load1: 8,
            ..base_supply()
        },
        d,
        ("light", true, 1, "impacted", "off", 5, "deep"),
    );
}

#[test]
fn demand_shrinks_the_batch_and_a_p0_rescues_a_light_cycle() {
    assert_plan(
        base_supply(),
        Demand {
            open_defects: 3,
            p0: 0,
        },
        ("normal", true, 2, "impacted", "loop", 3, "deep"),
    );
    // A P0 on a light tier buys a minimal fast cycle, not a skipped one.
    assert_plan(
        Supply {
            on_battery: true,
            ..base_supply()
        },
        Demand {
            open_defects: 3,
            p0: 2,
        },
        ("light", true, 1, "impacted", "off", 2, "fast"),
    );
    // A P0 on a healthy box changes nothing — the rescue is light-only.
    assert_plan(
        base_supply(),
        Demand {
            open_defects: 3,
            p0: 2,
        },
        ("normal", true, 2, "impacted", "loop", 3, "deep"),
    );
    // The light tier caps the batch at 5 whatever the queue holds.
    assert_plan(
        Supply {
            on_battery: true,
            ..base_supply()
        },
        Demand {
            open_defects: 9,
            p0: 0,
        },
        ("light", true, 1, "impacted", "off", 5, "deep"),
    );
}

proptest! {
    /// Demand can shrink a cycle, rescue a light one, or clamp the batch —
    /// but it never upgrades the tier, and the batch stays in range: at least
    /// 1, and at most 5 on the light tier.
    #[test]
    fn demand_never_upgrades_the_tier_and_the_batch_stays_in_range(
        cpu in 1u32..64, load1 in 0u32..80,
        mem_total in 1u64..256, mem_free in 0u64..256, disk in 0u64..500,
        battery in prop::bool::ANY, busy in prop::bool::ANY,
        defects in 0u32..300, p0 in 0u32..40,
    ) {
        let supply = Supply {
            cpu, load1,
            mem_total_gb: mem_total,
            mem_free_gb: mem_free.min(mem_total),
            disk_free_gb: disk,
            on_battery: battery,
            busy,
        };
        let demand = Demand { open_defects: defects, p0: p0.min(defects) };
        let with = plan_cycle(supply, demand, &ceilings(), Floors::default());
        let without = plan_cycle(supply, Demand::default(), &ceilings(), Floors::default());
        prop_assert_eq!(with.tier, without.tier, "demand moved the tier");
        prop_assert!(with.batch >= 1);
        if with.tier == Tier::Light {
            prop_assert!(with.batch <= 5, "light tier batch {} > 5", with.batch);
        }
    }
}

